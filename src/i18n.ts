const dict = { en, it };

export function detectLang(): Lang {
  try {
    const s = localStorage.getItem('justshare-lang');
    if (s === 'it' || s === 'en') return s;
  } catch {
    /* blocked */
  }
  return navigator.language?.toLowerCase().startsWith('it') ? 'it' : 'en';
}

export const translator = (lang: Lang) => (key: Key) => dict[lang][key] ?? en[key];
export type T = ReturnType<typeof translator>;
export const I18n = createContext<{ lang: Lang; t: T; setLang(l: Lang): void }>({ lang: 'en', t: translator('en'), setLang: () => {} });
export const useI18n = () => useContext(I18n);

export function formatBytes(n: number, lang: Lang): string {
  if (n < 1024) return `${n} B`;
  const u = ['KB', 'MB', 'GB'];
  let v = n / 1024;
  let i = 0;
  while (v >= 1024 && i < u.length - 1) {
    v /= 1024;
    i++;
  }
  return `${v.toLocaleString(lang, { maximumFractionDigits: v < 10 ? 1 : 0 })} ${u[i]}`;
}
